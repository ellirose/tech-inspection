// File storage for uploads. With the DO_SPACES_* variables set, files go to DigitalOcean Spaces (or any
// S3-compatible store, such as MinIO from docker-compose.yml); without them, to .data/uploads, so the panel
// works on a development machine. The bucket stays private: public files are served by the site's own
// routes (/media/uploads/…, /docs/uploads/…), so their URLs do not change if the storage does, and private
// files (quote attachments) are only reachable through short-lived links.
import "server-only";
import { createReadStream } from "node:fs";
import { mkdir, rm, stat, writeFile } from "node:fs/promises";
import { Readable } from "node:stream";
import path from "node:path";
import { DeleteObjectCommand, GetObjectCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";

/** `size` is the whole file; with a byte range, `range` is the part in `body` (both ends included). */
export type StoredFile = { body: ReadableStream | Uint8Array; size?: number; range?: { start: number; end: number } };
export type ByteRange = { start: number; end?: number };

type Driver = {
  put(key: string, body: Uint8Array, contentType: string): Promise<void>;
  /** With `range`, only those bytes (videos are played in ranges). */
  get(key: string, range?: ByteRange): Promise<StoredFile | null>;
  remove(key: string): Promise<void>;
};

const mimeByExt: Record<string, string> = { webp: "image/webp", jpg: "image/jpeg", jpeg: "image/jpeg", png: "image/png", pdf: "application/pdf", mp4: "video/mp4", webm: "video/webm" };
export const mimeOf = (key: string) => mimeByExt[key.split(".").pop()?.toLowerCase() ?? ""] ?? "application/octet-stream";

/** Keys are generated by the app (folders of lowercase letters, digits and dashes); anything else is refused. */
export const isStorageKey = (key: string) => /^[a-z]+(\/[a-z0-9-]+)*(\/[a-z0-9-]+\.[a-z0-9]+)$/.test(key) && !key.includes("..");

let client: S3Client | undefined;
function s3() {
  const endpoint = process.env.DO_SPACES_ENDPOINT!;
  return (client ??= new S3Client({
    endpoint,
    region: process.env.DO_SPACES_REGION || "us-east-1",
    // Spaces takes the bucket in the host name; MinIO and other stand-ins in the path.
    forcePathStyle: !endpoint.includes("digitaloceanspaces.com"),
    credentials: { accessKeyId: process.env.DO_SPACES_KEY!, secretAccessKey: process.env.DO_SPACES_SECRET! },
  }));
}

function s3Driver(): Driver {
  const bucket = process.env.DO_SPACES_BUCKET!;
  return {
    async put(key, body, contentType) {
      await s3().send(new PutObjectCommand({ Bucket: bucket, Key: key, Body: body, ContentType: contentType, ACL: "private" }));
    },
    async get(key, range) {
      try {
        const res = await s3().send(new GetObjectCommand({ Bucket: bucket, Key: key, Range: range ? `bytes=${range.start}-${range.end ?? ""}` : undefined }));
        if (!res.Body) return null;
        // "bytes 0-1023/52428800"
        const part = res.ContentRange?.match(/bytes (\d+)-(\d+)\/(\d+)/);
        if (part) return { body: res.Body.transformToWebStream(), size: Number(part[3]), range: { start: Number(part[1]), end: Number(part[2]) } };
        return { body: res.Body.transformToWebStream(), size: res.ContentLength };
      } catch (e) {
        if ((e as { name?: string }).name === "NoSuchKey") return null;
        throw e;
      }
    },
    async remove(key) {
      await s3().send(new DeleteObjectCommand({ Bucket: bucket, Key: key }));
    },
  };
}

function localDriver(): Driver {
  const root = path.resolve(".data/uploads");
  const file = (key: string) => path.join(root, ...key.split("/"));
  return {
    async put(key, body) {
      await mkdir(path.dirname(file(key)), { recursive: true });
      await writeFile(file(key), body);
    },
    async get(key, range) {
      let size;
      try {
        size = (await stat(file(key))).size;
      } catch {
        return null;
      }
      const part = range && size > 0 ? { start: range.start, end: Math.min(range.end ?? size - 1, size - 1) } : undefined;
      // Past the end: nothing to read (the caller answers 416).
      if (part && part.start > part.end) return { body: new Uint8Array(0), size };
      const stream = createReadStream(file(key), part);
      return { body: Readable.toWeb(stream) as ReadableStream, size, range: part };
    },
    async remove(key) {
      await rm(file(key), { force: true });
    },
  };
}

const usesSpaces = () => Boolean(process.env.DO_SPACES_ENDPOINT && process.env.DO_SPACES_BUCKET && process.env.DO_SPACES_KEY && process.env.DO_SPACES_SECRET);

let driver: Driver | undefined;
export const storage = () => (driver ??= usesSpaces() ? s3Driver() : localDriver());

/**
 * A link to a private file that stops working after `seconds`, for Spaces; null for local storage,
 * where the admin route streams the file itself after checking the session.
 */
export async function signedDownload(key: string, filename: string, seconds = 300): Promise<string | null> {
  if (!usesSpaces()) return null;
  const command = new GetObjectCommand({
    Bucket: process.env.DO_SPACES_BUCKET,
    Key: key,
    ResponseContentDisposition: `attachment; filename*=UTF-8''${encodeURIComponent(filename)}`,
  });
  return getSignedUrl(s3(), command, { expiresIn: seconds });
}
